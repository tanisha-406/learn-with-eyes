const CACHE_NAME = 'lwe-v2-cache';
const STATIC_ASSETS = [
  './',
  './index.html',
  './styles.css?v=2.0',
  './app.js?v=2.0',
  './manifest.json',
  './icon.svg'
];

// Install: Cache critical shell assets
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(STATIC_ASSETS).catch((err) => {
        console.warn('Non-critical asset cache failure:', err);
      });
    })
  );
  self.skipWaiting();
});

// Activate: Clean up old caches
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
      );
    })
  );
  self.clients.claim();
});

// Fetch: Cache-first for local static assets, network fallback
self.addEventListener('fetch', (event) => {
  // Do not intercept non-GET requests or YouTube / external cross-origin streams
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);

  // Exclude huge PDFs from service worker cache to prevent quota exhaustion
  if (url.pathname.endsWith('.pdf')) {
    return;
  }

  event.respondWith(
    caches.match(event.request).then((cachedResponse) => {
      if (cachedResponse) {
        return cachedResponse;
      }
      return fetch(event.request).then((networkResponse) => {
        // Cache successful same-origin responses
        if (networkResponse && networkResponse.status === 200 && url.origin === self.location.origin) {
          const responseToCache = networkResponse.clone();
          caches.open(CACHE_NAME).then((cache) => {
            cache.put(event.request, responseToCache);
          });
        }
        return networkResponse;
      }).catch(() => {
        // Fallback to cached index.html for navigation requests
        if (event.request.mode === 'navigate') {
          return caches.match('./index.html');
        }
      });
    })
  );
});
